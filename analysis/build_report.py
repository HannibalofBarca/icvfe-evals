"""
Builds analysis/output/report.md: a static Markdown report embedding the
figures from plotting.py and the total/task-level tables, with links to the
full CSVs for the granular (episode-level, 243-row) data.

Usage:
    python build_report.py
"""
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "output")

PAIR_ORDER = [
    "robodopamine_vs_human",
    "robometer_vs_human",
    "icvfe_vs_human",
    "recap_vs_human",
    "robometer_vs_robodopamine",
    "icvfe_vs_robodopamine",
    "recap_vs_robodopamine",
]
PAIR_LABELS = {
    "robodopamine_vs_human": "RoboDopamine vs Human",
    "robometer_vs_human": "RoboMeter vs Human",
    "icvfe_vs_human": "ICVFE vs Human",
    "recap_vs_human": "pi0.6-recap vs Human",
    "robometer_vs_robodopamine": "RoboMeter vs RoboDopamine",
    "icvfe_vs_robodopamine": "ICVFE vs RoboDopamine",
    "recap_vs_robodopamine": "pi0.6-recap vs RoboDopamine",
}


def fmt_table(df: pd.DataFrame) -> str:
    header = "| " + " | ".join(df.columns) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = []
    for _, r in df.iterrows():
        rows.append("| " + " | ".join(str(v) for v in r.values) + " |")
    return "\n".join([header, sep] + rows)


def build():
    total_wide = pd.read_csv(os.path.join(OUT_DIR, "total_level_wide.csv"))
    task_wide = pd.read_csv(os.path.join(OUT_DIR, "task_level_wide.csv"))
    episode_wide = pd.read_csv(os.path.join(OUT_DIR, "episode_level_wide.csv"))

    # ---- total-level summary table ----
    total_rows = []
    for pair in PAIR_ORDER:
        r = total_wide[total_wide["pair"] == pair].iloc[0]
        total_rows.append({
            "Pair": PAIR_LABELS[pair],
            "Pearson r": f"{r['pearson']:.3f}",
            "Kendall tau-b": f"{r['kendall_tau_b']:.3f}",
            "MAE": f"{r['mae']:.3f}",
            "n episodes": int(r["n_episodes"]),
        })
    total_table = fmt_table(pd.DataFrame(total_rows))

    # ---- task-level table, sorted by RoboDopamine-vs-Human Pearson ----
    tt = task_wide.sort_values("robodopamine_vs_human__pearson", ascending=False).copy()
    task_rows = []
    for _, r in tt.iterrows():
        row = {"Task": r["task"], "n eps": int(r["n_episodes"])}
        for pair in PAIR_ORDER:
            p = r[f"{pair}__pearson"]
            row[f"{PAIR_LABELS[pair]} r"] = f"{p:.3f}" if pd.notna(p) else "—"
        task_rows.append(row)
    task_table = fmt_table(pd.DataFrame(task_rows))

    n_manual = 243
    n_icvfe = 240
    n_recap = 240

    report = f"""# Evaluator Agreement — ICVFE Evals

How closely do four automatic progress evaluators — **RoboDopamine** (zero-shot),
**RoboMeter** (fine-tuned), **ICVFE** (in-context), and **pi0.6-recap**
(checkpoint step 20000, no-context) — track per-frame human progress
annotation on manipulation episodes, and each other?

Pearson r, Kendall's tau-b, and MAE, computed at episode / task / dataset
granularity across 27 tasks. MAE is in the same **0-1 fraction-of-task-progress**
units the annotations are natively defined in (progress ships as 0-100 in the
raw archives; that's itself just one normalization choice, so we divide by
100 rather than treat it as the "real" unit). Full methodology in
[`../README.md`](../README.md); this report is generated by `pipeline.py` ->
`plotting.py` -> `build_report.py`. Baseline-specific 3-way comparisons
(robometer / icvfe / recap vs robodopamine, and vs human) live in
[`vs_robodopamine/`](vs_robodopamine/) and [`vs_human/`](vs_human/); actual
overlaid progress curves (not just agreement stats) live in
[`progress_curves/`](progress_curves/).

- {n_manual} episodes have both human annotation and the two raw-curve automatic
  scorers (robodopamine, robometer); the `robodopamine_vs_human`,
  `robometer_vs_human`, and `robometer_vs_robodopamine` numbers use this set.
- ICVFE's own eval only covers {n_icvfe} of those {n_manual} episodes, and
  aggregates task/total numbers by **averaging its per-episode values**
  rather than pooling frames (it scores each episode against several
  in-context examples) — see the README's "ICVFE is handled differently"
  section before comparing its task/total numbers directly against the
  other pairs'.
- The ICVFE archive's own `target_progress` curve is **not** the human
  annotation — it's numerically identical (to float32 rounding) to
  RoboDopamine's curve for the same episode. `icvfe_vs_robodopamine` uses
  that curve directly (it's what ICVFE was natively scored against);
  `icvfe_vs_human` is computed separately by aligning ICVFE's prediction
  curve against the actual `manual` annotation. See the README for how this
  was verified.
- pi0.6-recap covers the same {n_recap} episodes as ICVFE and has the exact
  same target-curve caveat (its `target_progress` is robodopamine's curve too
  — same verification method). Unlike ICVFE it's a single no-context pass per
  episode (no in-context replicates to average), but its task/total numbers
  are aggregated the same way (averaging episode-level numbers) so the two
  are comparable in derivation.

## Dataset-wide agreement (total level)

{total_table}

![Total-level summary](figures/total_level_summary.png)

## Per-task agreement (task level)

Sorted by RoboDopamine-vs-Human Pearson r. Full per-task Pearson / Kendall /
MAE for all five pairs: [`task_level_wide.csv`](task_level_wide.csv).

{task_table}

![Task-level Pearson r](figures/task_level_pearson.png)

![Task-level Kendall tau-b](figures/task_level_kendall.png)

![Task-level MAE](figures/task_level_mae.png)

## Per-episode agreement (episode level)

{n_manual} episodes ({n_icvfe} for the ICVFE pair) is too granular for a
readable bar chart per episode, so the full per-episode numbers live in
[`episode_level_wide.csv`](episode_level_wide.csv) (one row per episode, one
column per pair x metric) and [`metrics_long.csv`](metrics_long.csv) (long
format, all levels/pairs/metrics — filter this for anything). The charts
below show the *distribution* of episode-level values per pair, as a graph
complement to that table.

![Episode-level Pearson r distribution](figures/episode_distribution_pearson.png)

![Episode-level Kendall tau-b distribution](figures/episode_distribution_kendall.png)

![Episode-level MAE distribution](figures/episode_distribution_mae.png)
"""

    out_path = os.path.join(OUT_DIR, "report.md")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(report)
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    build()
